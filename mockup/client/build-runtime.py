#!/usr/bin/env python3
"""Bundle the checked-in source design boards; no network or packages needed."""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent
boards = {}
for path in sorted((root / "boards").glob("*.html")):
    source = path.read_text()
    body = re.search(r"<body[^>]*>(.*?)</body>", source, flags=re.S | re.I)
    title = re.search(r"<title>(.*?)</title>", source, flags=re.S | re.I)
    if not body:
        raise SystemExit(f"Missing source body: {path}")
    boards[path.name] = {
        "body": body.group(1),
        "style": "\n".join(re.findall(r"<style[^>]*>(.*?)</style>", source, flags=re.S | re.I)),
        "title": title.group(1) if title else path.stem,
    }
if len(boards) != 26:
    raise SystemExit(f"Expected 26 boards, found {len(boards)}")
payload = json.dumps(boards, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
output = root / "assets/runtime-boards.js"
output.write_text("/* Generated by client/build-runtime.py from the original design boards. */\nwindow.PG_CLIENT_BOARDS=" + payload + ";\n")
print(f"Bundled {len(boards)} source boards: {output.stat().st_size:,} bytes")
